'use strict';

const router = require('express').Router();
const { requireAuth } = require('../middleware/auth');
const room = require('../room/manager');

const I18N = {
  zh: {
    notExist: '会话不存在或已销毁',
    alreadyDestroyed: '会话已销毁，无法导出',
    header: '临时会话：',
    creator: '创建者',
    createdAt: '创建时间',
    destroyAt: '销毁时间',
    remaining: '剩余',
    remainingUnit: '秒',
    members: '成员',
    msgCount: '消息数',
    records: '会话记录',
    footer: '本会话由「有内鬼」生成，已导出后内容与线上会话无关',
    exportTime: '导出时间',
  },
  en: {
    notExist: 'Room does not exist or already destroyed',
    alreadyDestroyed: 'Room already destroyed, cannot export',
    header: 'Ephemeral Room: ',
    creator: 'Creator',
    createdAt: 'Created at',
    destroyAt: 'Destroy at',
    remaining: 'Remaining',
    remainingUnit: 's',
    members: 'Members',
    msgCount: 'Messages',
    records: 'Chat Records',
    footer: 'Generated by YouNeiGui. Exported content is independent of the live room.',
    exportTime: 'Exported at',
  },
};

function formatSize(bytes) {
  if (bytes < 1024) return bytes + ' B';
  if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + ' KB';
  return (bytes / 1024 / 1024).toFixed(1) + ' MB';
}

// GET /api/export/:roomId?lang=en — 导出 Markdown
router.get('/:roomId', requireAuth, async (req, res) => {
  const lang = (req.query.lang === 'en' ? 'en' : 'zh');
  const t = I18N[lang];
  const dateLocale = lang === 'en' ? 'en-US' : 'zh-CN';

  const roomData = await room.getRoom(req.params.roomId);
  if (!roomData) return res.status(404).send(t.notExist);
  if (roomData.status !== 'active') return res.status(410).send(t.alreadyDestroyed);

  const now = new Date();
  const fmt = (ts) => new Date(ts).toLocaleString(dateLocale, { hour12: false });

  const lines = [];
  lines.push(`# ${t.header}${roomData.topic}`);
  lines.push('');
  lines.push(`- ${t.creator}: ${roomData.creatorNickname}`);
  lines.push(`- ${t.createdAt}: ${fmt(roomData.createdAt)}`);
  lines.push(`- ${t.destroyAt}: ${fmt(roomData.destroyAt)} (${t.remaining} ${roomData.remainingSeconds} ${t.remainingUnit})`);
  lines.push(`- ${t.members}: ${roomData.members.map(m => m.nickname).join(lang === 'en' ? ', ' : '、')}`);
  lines.push(`- ${t.msgCount}: ${roomData.messages.length}`);
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push(`## ${t.records}`);

  const groups = {};
  for (const msg of roomData.messages) {
    const dateKey = new Date(msg.timestamp).toLocaleDateString(dateLocale);
    if (!groups[dateKey]) groups[dateKey] = [];
    groups[dateKey].push(msg);
  }

  for (const [dateKey, msgs] of Object.entries(groups)) {
    lines.push('');
    lines.push(`### ${dateKey}`);
    for (const msg of msgs) {
      const time = new Date(msg.timestamp).toLocaleTimeString(dateLocale, { hour12: false, hour: '2-digit', minute: '2-digit' });
      lines.push('');
      if (lang === 'en') {
        lines.push(`**${msg.sender_nickname}** @ ${time}:`);
      } else {
        lines.push(`**${msg.sender_nickname}** @ ${time}：`);
      }

      // 已撤回
      if (msg.type === 'revoked') {
        lines.push(`> ~~— ${lang === 'en' ? 'A message was revoked —' : '— 一条消息已被撤回 —'}~~`);
        continue;
      }

      // media 消息：按类型渲染 Markdown
      if (msg.type === 'image') {
        lines.push(`> 🖼️ ![${msg.original_name || 'image'}](${msg.public_url})`);
        if (msg.original_name) lines.push(`> \`${msg.original_name}\``);
      } else if (msg.type === 'audio') {
        lines.push(`> 🎵 **${lang === 'en' ? 'Audio' : '音频'}**: [${msg.original_name || 'audio'}](${msg.public_url})  \`${msg.size ? formatSize(msg.size) : ''}\``);
      } else if (msg.type === 'video') {
        lines.push(`> 🎬 **${lang === 'en' ? 'Video' : '视频'}**: [${msg.original_name || 'video'}](${msg.public_url})  \`${msg.size ? formatSize(msg.size) : ''}\``);
      } else if (msg.type === 'document') {
        const displayName = msg.original_name || (msg.file_key || '').split('/').pop() || 'document';
        lines.push(`> 📄 **${lang === 'en' ? 'Document' : '文档'}**: [${displayName}](${msg.public_url})  \`${msg.size ? formatSize(msg.size) : ''}\``);
      } else {
        // text / 旧消息
        const content = msg.content || msg.message || '';
        for (const line of content.split('\n')) lines.push(`> ${line}`);
      }
    }
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push(`> ${t.footer}`);
  lines.push(`> ${t.exportTime}: ${fmt(now.getTime())}`);

  const md = lines.join('\n');

  const safeTopic = roomData.topic.replace(/[\\/:*?"<>|]/g, '_').slice(0, 50);
  const filename = `${safeTopic}_${now.toISOString().slice(0, 19).replace(/[:T]/g, '-')}.md`;

  res.setHeader('Content-Type', 'text/markdown; charset=utf-8');
  res.setHeader('Content-Disposition', `attachment; filename="${encodeURIComponent(filename)}"`);
  res.send(md);
});

module.exports = router;
